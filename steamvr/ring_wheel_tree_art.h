#pragma once
// Ring skill menu tree icons: the tree
// mark's picture, one painted rust square per skill tree (24: 8 classes x 3 trees), our own art,
// in full color. Today's mark is the kit's drawn glyph (TreeGlyphOf, RecipeTreeGlyph); this header is the painted picture's side:
//   - the slot of a (class, position): class x 3 + the tree's skillcategories page (PageAt), -1 for an unknown class;
//   - the sheet: steamvr/assets/ring-wheel/ring-tree-sheet.png, 6 x 4 cells of CellPx, cell = slot (row-major), built by
//     tools/ring_tree_sheet.py from 24 source squares (borderless full-bleed rust, motif in the middle 80%: no frame, bevel or
//     rivets of its own, so the square mode's plate frame is drawn in code, RecipeSquare); an unpainted slot's
//     cell is left fully transparent, and PaintedMask (steamvr/ring_wheel_tree_sheet.h, written by the same script) names the
//     painted ones, so the sheet works with 0, 3 or 24 squares and nothing decodes it on the frame thread to know;
//   - the atlas id of a slot (ArtId, 9200 up: our art, never keyed, ring_wheel_unbake.h) and the slice that serves it;
//   - the ring rows' reading: Mode (Drawn / Painted circle / Painted square) and the size (25..300%, 0 hides the mark).
// A slot with no painted square keeps the drawn glyph (the fallback is the draw path's: no cell, no picture).
// The file names the script and the use are FileName(slot): tree-<class>-<tree>.png in kebab case.
#include <algorithm>
#include <array>
#include <cmath>
#include <cstdint>
#include <memory>
#include <string>
#include "interaction_icons.h"   // the Image the atlas worker packs
#include "ring_wheel.h"
#include "ring_wheel_tree_sheet.h"   // PaintedMask: generated by tools/ring_tree_sheet.py

namespace framevr::ringwheel::treeart {
using Image = interaction::icons::Image;
constexpr int Classes = 8, Count = Classes * Trees;   // 24 trees
constexpr int ArtFirst = 9200;                          // the atlas ids ArtFirst.. ArtFirst + Count - 1 (ring_wheel_unbake.h OurArtFirst 9000 and up)
constexpr int SheetCols = 6, SheetRows = 4, CellPx = 144, SheetW = SheetCols * CellPx, SheetH = SheetRows * CellPx;
static_assert(SheetCols * SheetRows == Count, "one sheet cell per tree");
inline constexpr const wchar_t* ResourceName = L"D2RVR_RING_TREE_SHEET";   // RCDATA in steamvr/ring_wheel_menu_art.rc

// Mode, the ring row's list: Drawn is today's glyph (its Off value).
enum class Mode : int { Drawn = 0, Circle = 1, Square = 2 };
inline constexpr const char* ModeName[3] = {"Drawn", "Painted circle", "Painted square"};
inline Mode ModeOf(float v) { return v >= 1.5f ? Mode::Square : v >= .5f ? Mode::Circle : Mode::Drawn; }
// Size row: 25..300% of today's mark (100 = today's), 0 hides the mark. A value between 0 and 25 reads as 25 (the least that
// still shows); anything past 300 or not a number reads as 100.
constexpr int SizeMin = 25, SizeMax = 300, SizeDefault = 100;
inline int SizePct(float v) {
    if (!std::isfinite(v)) return SizeDefault;
    if (v <= 0) return 0;
    return std::clamp(int(std::lround(v)), SizeMin, SizeMax);
}
inline float SizeScale(float v) { return float(SizePct(v)) / 100.f; }

// The trees, in skillcategories page order per class (the kit's trees[i]): class, tree.
struct TreeName { const char* cls; const char* tree; };
inline constexpr std::array<TreeName, Count> Names{{
    {"amazon", "bow-and-crossbow"}, {"amazon", "passive-and-magic"}, {"amazon", "javelin-and-spear"},
    {"sorceress", "fire"}, {"sorceress", "lightning"}, {"sorceress", "cold"},
    {"necromancer", "curses"}, {"necromancer", "poison-and-bone"}, {"necromancer", "summoning"},
    {"paladin", "combat"}, {"paladin", "offensive-auras"}, {"paladin", "defensive-auras"},
    {"barbarian", "combat"}, {"barbarian", "combat-masteries"}, {"barbarian", "warcries"},
    {"druid", "summoning"}, {"druid", "shape-shifting"}, {"druid", "elemental"},
    {"assassin", "traps"}, {"assassin", "shadow-disciplines"}, {"assassin", "martial-arts"},
    {"warlock", "demon"}, {"warlock", "eldritch"}, {"warlock", "chaos"}}};
inline std::string FileName(int slot) { return slot >= 0 && slot < Count ? std::string("tree-") + Names[size_t(slot)].cls + "-" + Names[size_t(slot)].tree + ".png" : std::string(); }

// The slot of a class's tree at a wheel position (position -> its page, as TreeGlyphOf reads it); -1: no such tree (an unknown class).
inline int Slot(int skillClass, int position) {
    if (skillClass < 0 || skillClass >= Classes || position < 0 || position >= Trees) return -1;
    return skillClass * Trees + PageAt(skillClass, position);
}
inline int ArtId(int slot) { return slot >= 0 && slot < Count ? ArtFirst + slot : -1; }
inline int SlotOfArt(int id) { return id >= ArtFirst && id < ArtFirst + Count ? id - ArtFirst : -1; }
// Which slots are painted: the built sheet's PaintedMask; the tests and the preview set another (a stand-in set of 0, 3 or 24) with SetMask.
inline uint32_t& MaskRef() { static uint32_t m = PaintedMask; return m; }
inline void SetMask(uint32_t m) { MaskRef() = m & ((1u << Count) - 1); }
inline bool Painted(int slot) { return slot >= 0 && slot < Count && (MaskRef() >> slot & 1u) != 0; }
inline bool PaintedAt(int skillClass, int position) { return Painted(Slot(skillClass, position)); }
inline int PaintedCount() { int n = 0; for (int s = 0; s < Count; ++s) n += Painted(s); return n; }
inline int PaintedInClass(int skillClass) {
    int n = 0;
    for (int p = 0; p < Trees; ++p) n += PaintedAt(skillClass, p);
    return n;
}
// Whether this tree draws a painted picture now: the mode asks for one and its square is in the sheet. Else the drawn glyph.
inline bool UsesPainted(Mode mode, int skillClass, int position) { return mode != Mode::Drawn && PaintedAt(skillClass, position); }

// A sheet cell's top left, in sheet px.
inline void CellOrigin(int slot, int& x, int& y) { x = (slot % SheetCols) * CellPx; y = (slot / SheetCols) * CellPx; }

// One slot's picture cut from the decoded sheet (CellPx square, straight RGBA); null when the sheet is the wrong shape, the slot
// is out of range, or the cell holds no pixel (an unpainted cell).
inline std::shared_ptr<const Image> Slice(const Image& sheet, int slot) {
    if (slot < 0 || slot >= Count || sheet.width != unsigned(SheetW) || sheet.height != unsigned(SheetH) || sheet.rgba.size() < size_t(SheetW) * SheetH * 4) return nullptr;
    int x0, y0; CellOrigin(slot, x0, y0);
    auto out = std::make_shared<Image>();
    out->width = out->height = CellPx;
    out->rgba.resize(size_t(CellPx) * CellPx * 4);
    bool any = false;
    for (int y = 0; y < CellPx; ++y) {
        const uint8_t* src = &sheet.rgba[(size_t(y0 + y) * SheetW + size_t(x0)) * 4];
        std::copy(src, src + size_t(CellPx) * 4, &out->rgba[size_t(y) * CellPx * 4]);
        for (int x = 0; x < CellPx && !any; ++x) any = src[x * 4 + 3] != 0;
    }
    return any ? out : nullptr;
}


// The ids the atlas should hold for this class: its painted trees' (up to three), appended to `ids` after the seats. Returns the new n.
// Nothing while the mode is Drawn or the size hides the mark: the Off path asks for no cell.
inline int AddIcons(Mode mode, int sizePct, int skillClass, int* ids, int n, int cap) {
    if (mode == Mode::Drawn || sizePct <= 0) return n;
    for (int p = 0; p < Trees; ++p) {
        const int slot = Slot(skillClass, p);
        if (!Painted(slot)) continue;
        const int id = ArtId(slot);
        if (n < cap && std::find(ids, ids + n, id) == ids + n) ids[n++] = id;
    }
    return n;
}
}  // namespace framevr::ringwheel::treeart
