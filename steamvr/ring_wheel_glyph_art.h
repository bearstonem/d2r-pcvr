#pragma once
// Ring skill menu > Center > Glyph icon (the player 5:49 PM: "glyph icons are claude drawings, lets see what gpt can do to make them
// look d2 style with the rust and silver, we need the square as the basic, and then we need to make a circle version for our ring
// menu"): the pictures that replace the ring wheel's code-drawn glyphs, 12 of them, our own art:
//   - slots 0-7 the Glyphs page's shape faces, in glyphs::Shape order (circle, triangle, square, lightning bolt, spiral, V, star, wave);
//   - slots 8-11 the center split's sigils (Sigil::Back, Cross = "clear", Star, Hand).
// Same plan as the tree icons (steamvr/ring_wheel_tree_art.h): the sheet steamvr/assets/ring-wheel/ring-glyph-sheet.png, 4 x 3 cells of CellPx,
// cell = slot (row-major), built by tools/ring_glyph_sheet.py from tools/ring_glyph_squares (borderless full-bleed rust squares with a
// silver motif in the middle 80%); an unpainted slot's cell is fully transparent and its bit in PaintedMask
// (steamvr/ring_wheel_glyph_sheet.h, written by the same script) is clear, so the sheet works with 0, 3 or 12 squares and the engine
// keeps the drawn shape or sigil for every slot with no square. The atlas ids are 9300 up (our art: never keyed, ring_wheel_unbake.h).
// Mode (Drawn / Painted circle / Painted square) and the size row (25..300%) are the ring rows' reading.
#include <algorithm>
#include <array>
#include <cmath>
#include <cstdint>
#include <memory>
#include <string>
#include "interaction_icons.h"   // the Image the atlas worker packs
#include "ring_wheel_glyph_sheet.h"   // PaintedMask: generated by tools/ring_glyph_sheet.py

namespace framevr::ringwheel::glyphart {
using Image = interaction::icons::Image;
constexpr int Shapes = 8, Sigils = 4, Count = Shapes + Sigils;
constexpr int ArtFirst = 9300;   // the atlas ids ArtFirst.. ArtFirst + Count - 1 (tree art 9200.. 9223, the sub-menus 9101.. 9103)
constexpr int SheetCols = 4, SheetRows = 3, CellPx = 144, SheetW = SheetCols * CellPx, SheetH = SheetRows * CellPx;
static_assert(SheetCols * SheetRows == Count, "one sheet cell per picture");
inline constexpr const wchar_t* ResourceName = L"D2RVR_RING_GLYPH_SHEET";   // RCDATA in steamvr/ring_wheel_menu_art.rc
constexpr int SlotBack = 8, SlotClear = 9, SlotStar = 10, SlotHand = 11;
constexpr float SigilPx = 34;   // a painted sigil's outer size at 100% (the drawn one is 20 px of strokes)

enum class Mode : int { Drawn = 0, Circle = 1, Square = 2 };
inline constexpr const char* ModeName[3] = {"Drawn", "Painted circle", "Painted square"};
inline Mode ModeOf(float v) { return v >= 1.5f ? Mode::Square : v >= .5f ? Mode::Circle : Mode::Drawn; }
// Size row: 25..300% of the drawn one (100 = today's size); a value under 25 reads as 25, past 300 or not a number as 100. Off is the mode.
constexpr int SizeMin = 25, SizeMax = 300, SizeDefault = 100;
inline int SizePct(float v) {
    if (!std::isfinite(v)) return SizeDefault;
    return std::clamp(int(std::lround(v)), SizeMin, SizeMax);
}
inline float SizeScale(float v) { return float(SizePct(v)) / 100.f; }

struct GlyphName { const char* kind; const char* name; };
inline constexpr std::array<GlyphName, Count> Names{{
    {"glyph", "circle"}, {"glyph", "triangle"}, {"glyph", "square"}, {"glyph", "lightning"}, {"glyph", "spiral"}, {"glyph", "v"}, {"glyph", "star"}, {"glyph", "wave"},
    {"sigil", "back"}, {"sigil", "clear"}, {"sigil", "star"}, {"sigil", "hand"}}};
inline std::string FileName(int slot) { return slot >= 0 && slot < Count ? std::string(Names[size_t(slot)].kind) + "-" + Names[size_t(slot)].name + ".png" : std::string(); }

inline int ArtId(int slot) { return slot >= 0 && slot < Count ? ArtFirst + slot : -1; }
inline int SlotOfArt(int id) { return id >= ArtFirst && id < ArtFirst + Count ? id - ArtFirst : -1; }
// Which slots are painted: the built sheet's PaintedMask; the tests and the preview set another (a stand-in set of 0, 3 or 12) with SetMask.
inline uint32_t& MaskRef() { static uint32_t m = PaintedMask; return m; }
inline void SetMask(uint32_t m) { MaskRef() = m & ((1u << Count) - 1); }
inline bool Painted(int slot) { return slot >= 0 && slot < Count && (MaskRef() >> slot & 1u) != 0; }
inline int PaintedCount() { int n = 0; for (int s = 0; s < Count; ++s) n += Painted(s); return n; }

// What the draw reads: the mode, the size and each slot's atlas cell (-1: none, the drawn glyph or sigil stays).
struct View {
    int mode = 0;                       // Mode
    int sizePct = SizeDefault;
    std::array<int16_t, Count> cell = [] { std::array<int16_t, Count> a; a.fill(-1); return a; }();
    bool Shows(int slot) const { return mode != 0 && slot >= 0 && slot < Count && cell[size_t(slot)] >= 0; }
    float Scale() const { return float(SizePct(float(sizePct))) / 100.f; }
    bool operator==(const View&) const = default;
};

// A sheet cell's top left, in sheet px.
inline void CellOrigin(int slot, int& x, int& y) { x = (slot % SheetCols) * CellPx; y = (slot / SheetCols) * CellPx; }
// One slot's picture cut from the decoded sheet (CellPx square, straight RGBA); null when the sheet is the wrong shape, the slot is
// out of range, or the cell holds no pixel (an unpainted cell).
inline std::shared_ptr<const Image> Slice(const Image& sheet, int slot) {
    if (slot < 0 || slot >= Count || sheet.width != unsigned(SheetW) || sheet.height != unsigned(SheetH) || sheet.rgba.size() < size_t(SheetW) * SheetH * 4) return nullptr;
    int x0, y0; CellOrigin(slot, x0, y0);
    auto out = std::make_shared<Image>();
    out->width = out->height = CellPx;
    out->rgba.resize(size_t(CellPx) * CellPx * 4);
    bool any = false;
    for (int y = 0; y < CellPx; ++y) {
        const uint8_t* src = &sheet.rgba[(size_t(y0 + y) * SheetW + size_t(x0)) * 4];
        std::copy(src, src + size_t(CellPx) * 4, &out->rgba[size_t(y) * CellPx * 4]);
        for (int x = 0; x < CellPx && !any; ++x) any = src[x * 4 + 3] != 0;
    }
    return any ? out : nullptr;
}

// The ids the atlas should hold: every painted slot's, appended to `ids` after the seats (cap-guarded). Returns the new n. Nothing
// while the mode is Drawn: the Off path asks for no cell.
inline int AddIcons(Mode mode, int* ids, int n, int cap) {
    if (mode == Mode::Drawn) return n;
    for (int slot = 0; slot < Count; ++slot) {
        if (!Painted(slot)) continue;
        const int id = ArtId(slot);
        if (n < cap && std::find(ids, ids + n, id) == ids + n) ids[n++] = id;
    }
    return n;
}
}  // namespace framevr::ringwheel::glyphart
