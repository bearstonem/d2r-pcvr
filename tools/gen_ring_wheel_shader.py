"""Lab Ring wheel (T025, R8 match stage 1a perf fix): compiles the compose pass's shaders once, at build time.

The compose shader (vr/ring_wheel_compose.cpp `Source`, after steamvr/ring_wheel_skill_fx.h `RestLayersHlsl`) takes
15-20 s to compile at /O3 since R8 match stage 1a; at run time that was the wait on
every Lab On edge. The build runs this (steamvr/lab.cmake) and writes <build>/generated/ring_wheel_shader_blob.h: the
FNV-1a 64 hash of the exact source the Lab compiles, the VS and PS bytecode (fxc /O3, the same d3dcompiler as D3DCompile)
and the PS instruction-slot count; nothing binary goes into git. At run time a matching hash uses the bytecode (no compile).
No fxc on the build machine: an empty blob (ShaderBlobOk false), and the Lab compiles at run time as before.
Two pixel shaders (R8 match stage 2): PS (icons, rings, text) and PSFx (the effects, recipe 6); each must stay within
SLOT_BUDGET (the build fails): the recipe tables are data and must not grow the code.

    python tools/gen_ring_wheel_shader.py --out <header> [--fxc <fxc.exe>]
"""
import glob
import os
import pathlib
import re
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
SLOT_BUDGET = 3400   # the PS slot ceiling; the recipe tables are data and must not grow the code
# Temps per pixel shader (perf 1b finding 3: occupancy follows the biggest branch's registers). PS (every icon, ring and
# glyph) 24; PSFx 32: only effect pixels run at its occupancy since the split (stage 2: 29 with the pointed defaults).
TEMP_BUDGET = {'PS': 24, 'PSFx': 32}
SDK_BIN = os.path.join('C:' + os.sep, 'Program Files (x86)', 'Windows Kits', '10', 'bin')


def raw_string(text, name):
    m = re.search(name + r'\[\] = R"\((.*?)\)";', text, re.S)
    if not m:
        raise SystemExit(f"{name}: raw string not found")
    return m.group(1).replace('\r\n', '\n')


def fnv64(data):
    h = 0xcbf29ce484222325
    for b in data:
        h ^= b
        h = (h * 0x100000001b3) & 0xFFFFFFFFFFFFFFFF
    return h


def listing_numbers(text, entry):
    """A pixel shader's instruction slots and temps from fxc's /Fc listing. A listing without the slot line (an fxc that
    words it otherwise) fails the build: read as 0 it would pass any budget (review N7)."""
    m = re.search(r'Approximately (\d+) instruction slots', text)
    if not m:
        raise SystemExit(f'ring wheel compose: no instruction-slot line in fxc\'s listing for {entry} (tools/gen_ring_wheel_shader.py)')
    t = re.search(r'dcl_temps (\d+)', text)
    return int(m.group(1)), int(t.group(1)) if t else 0


def self_test():
    """ctest ring-wheel-shader-gen-test: the listing parser reads both numbers and refuses a listing with no slot line."""
    ok = listing_numbers('dcl_temps 14\n// Approximately 876 instruction slots used', 'PS') == (876, 14)
    try:
        listing_numbers('dcl_temps 14\n// 876 instructions', 'PS')
        ok = False
    except SystemExit:
        pass
    print('gen_ring_wheel_shader self-test', 'passed' if ok else 'FAILED')
    return 0 if ok else 1


def arg(name):
    return sys.argv[sys.argv.index(name) + 1] if name in sys.argv else None


def find_fxc():
    given = arg('--fxc')
    if given and os.path.exists(given):
        return given
    found = sorted(glob.glob(os.path.join(SDK_BIN, '10.*', 'x64', 'fxc.exe')))
    return found[-1] if found else None


def shader_constants():
    """Review N1: the HLSL's copies of ring_wheel_draw.h's constants, the same line as the C++ ShaderConstants()."""
    text = (ROOT / 'steamvr' / 'ring_wheel_draw.h').read_text('ascii')
    v = {}
    for name in ('PointedReachPx', 'PointedEdgePx'):
        m = re.search(name + r' = (\d+)\b', text)
        if not m:
            raise SystemExit(f'{name}: not found in steamvr/ring_wheel_draw.h (tools/gen_ring_wheel_shader.py)')
        v[name] = int(m.group(1))
    return f"static const float PointedReachPx = {v['PointedReachPx']}, PointedEdgePx = {v['PointedEdgePx']};\n"


def main():
    source = shader_constants() + raw_string((ROOT / 'steamvr' / 'ring_wheel_skill_fx.h').read_text('ascii'), 'RestLayersHlsl') + \
        raw_string((ROOT / 'vr' / 'ring_wheel_compose.cpp').read_text('ascii'), 'Source')
    data = source.encode('ascii')
    out = pathlib.Path(arg('--out') or (ROOT / 'build-frame' / 'ring_wheel_shader_blob.h'))
    out.parent.mkdir(parents=True, exist_ok=True)
    head = ['#pragma once',
            "// Lab Ring wheel (T025): the compose pass's shaders, compiled offline (fxc /O3) at build time. GENERATED by",
            '// tools/gen_ring_wheel_shader.py from vr/ring_wheel_compose.cpp Source and steamvr/ring_wheel_skill_fx.h RestLayersHlsl.',
            'namespace framevr::ringwheel {']
    fxc = find_fxc()
    if not fxc:
        out.write_bytes('\r\n'.join(head + [
            'inline constexpr bool ShaderBlobOk = false;   // no fxc on the build machine: the Lab compiles at run time',
            'inline constexpr unsigned long long ShaderBlobHash = 0;',
            f'inline constexpr unsigned ShaderBlobPsSlots = 0, ShaderBlobPsFxSlots = 0, ShaderBlobSlotBudget = {SLOT_BUDGET};',
            f'inline constexpr unsigned ShaderBlobPsTemps = 0, ShaderBlobPsFxTemps = 0, ShaderBlobPsTempBudget = {TEMP_BUDGET["PS"]}, ShaderBlobPsFxTempBudget = {TEMP_BUDGET["PSFx"]};',
            'inline constexpr unsigned char ShaderBlobVs[1] = {0}, ShaderBlobPs[1] = {0}, ShaderBlobPsFx[1] = {0};',
            '}  // namespace framevr::ringwheel', '']).encode('ascii'))
        print(f'{out}: no fxc, an empty blob (the Lab compiles at run time)')
        return
    blobs, slots, temps = {}, {}, {}
    with tempfile.TemporaryDirectory() as tmp:
        src = os.path.join(tmp, 'ring-wheel-compose.hlsl')
        with open(src, 'wb') as f:
            f.write(data)
        for entry, target in (('VS', 'vs_5_0'), ('PS', 'ps_5_0'), ('PSFx', 'ps_5_0')):
            cso, asm = os.path.join(tmp, entry + '.cso'), os.path.join(tmp, entry + '.asm')
            r = subprocess.run([fxc, '/nologo', '/T', target, '/E', entry, '/O3', '/Fo', cso, '/Fc', asm, src], capture_output=True, text=True)
            if r.returncode != 0:
                raise SystemExit(r.stdout + r.stderr)
            blobs[entry] = open(cso, 'rb').read()
            if entry != 'VS':
                slots[entry], temps[entry] = listing_numbers(open(asm).read(), entry)
    for entry, n in slots.items():
        if n > SLOT_BUDGET:
            raise SystemExit(f'ring wheel compose: pixel shader {entry} {n} slots, over the {SLOT_BUDGET} budget (tools/gen_ring_wheel_shader.py)')
    for entry, n in temps.items():
        if n > TEMP_BUDGET[entry]:
            raise SystemExit(f'ring wheel compose: pixel shader {entry} {n} temps, over the {TEMP_BUDGET[entry]} budget (tools/gen_ring_wheel_shader.py)')

    def arr(name, b):
        rows = [', '.join(f'0x{x:02X}' for x in b[i:i + 24]) for i in range(0, len(b), 24)]
        return [f'inline constexpr unsigned char {name}[{len(b)}] = {{'] + ['    ' + r + ',' for r in rows] + ['};']
    lines = head + ['inline constexpr bool ShaderBlobOk = true;',
                    f'inline constexpr unsigned long long ShaderBlobHash = 0x{fnv64(data):016X}ull;   // FNV-1a 64 of the source',
                    f'inline constexpr unsigned ShaderBlobPsSlots = {slots["PS"]}, ShaderBlobPsFxSlots = {slots["PSFx"]}, ShaderBlobSlotBudget = {SLOT_BUDGET};',
                    f'inline constexpr unsigned ShaderBlobPsTemps = {temps["PS"]}, ShaderBlobPsFxTemps = {temps["PSFx"]}, ShaderBlobPsTempBudget = {TEMP_BUDGET["PS"]}, ShaderBlobPsFxTempBudget = {TEMP_BUDGET["PSFx"]};',
                    *arr('ShaderBlobVs', blobs['VS']), *arr('ShaderBlobPs', blobs['PS']), *arr('ShaderBlobPsFx', blobs['PSFx']),
                    '}  // namespace framevr::ringwheel', '']
    out.write_bytes('\r\n'.join(lines).encode('ascii'))
    print(f'{out}: hash {fnv64(data):016X}, VS {len(blobs["VS"])} bytes, PS {len(blobs["PS"])} bytes {slots["PS"]} slots, '
          f'PSFx {len(blobs["PSFx"])} bytes {slots["PSFx"]} slots, temps {temps["PS"]} + {temps["PSFx"]} (budgets {SLOT_BUDGET} slots, {TEMP_BUDGET["PS"]} + {TEMP_BUDGET["PSFx"]} temps)')


if __name__ == '__main__':
    sys.exit(self_test()) if '--self-test' in sys.argv else main()
